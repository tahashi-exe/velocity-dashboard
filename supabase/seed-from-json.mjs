// One-time import of clubs.json + events.json into the `runs` table
// (TECHNICAL.md §6). Prints SQL to stdout:
//
//   node supabase/seed-from-json.mjs > supabase/seed.sql
//
// Re-run it on cutover day so records the bot added in the meantime come
// across too. It upserts on `slug`, so running the output twice is harmless.
//
// The record -> row mapping is shared with the Telegram bot
// (telegram-bot/src/run-row.js), so a seeded run and one the bot publishes
// are built by the same code and get the same slug.

import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { toRunRow } from '../telegram-bot/src/run-row.js'

const root = new URL('..', import.meta.url)
const readJson = name => JSON.parse(readFileSync(fileURLToPath(new URL(name, root)), 'utf8'))

const sql = v => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'boolean' || typeof v === 'number') return String(v)
  return `'${String(v).replace(/'/g, "''")}'`
}
const sqlArray = arr => `array[${arr.map(sql).join(', ')}]::text[]`

const rows = [
  ...readJson('clubs.json').map(c => toRunRow(c, 'recurring')),
  ...readJson('events.json').map(e => toRunRow(e, 'one_off')),
]

const slugs = rows.map(r => r.slug)
const dupes = slugs.filter((s, i) => slugs.indexOf(s) !== i)
if (dupes.length) {
  console.error(`Duplicate slugs (two records share a name): ${[...new Set(dupes)].join(', ')}`)
  process.exit(1)
}

const columns = Object.keys(rows[0])
const values = rows.map(r => `  (${columns.map(c => {
  if (c === 'photos') return sqlArray(r.photos)
  if (c === 'details') return `${sql(JSON.stringify(r.details))}::jsonb`
  if (c === 'kind') return `${sql(r.kind)}::public.run_kind`
  return sql(r[c])
}).join(', ')})`)

console.log(`-- Generated by supabase/seed-from-json.mjs from clubs.json + events.json.
-- ${rows.length} runs. Safe to re-run: upserts on slug.

insert into public.runs (${columns.join(', ')}) values
${values.join(',\n')}
on conflict (slug) do update set
${columns.filter(c => c !== 'slug').map(c => `  ${c} = excluded.${c}`).join(',\n')};`)
